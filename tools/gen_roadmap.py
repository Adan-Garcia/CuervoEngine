#!/usr/bin/env python3
"""Generates the public roadmap (docs/ROADMAP.md) from the milestones table.

    python3 -I tools/gen_roadmap.py --write    # regenerate docs/ROADMAP.md
    python3 -I tools/gen_roadmap.py --check    # exit 1 when it is out of date (the ctest)

docs/DESIGN.md section 6 is the one source of truth (milestone 10.5d): each
row has a number, a phase ("**Title** (section): scope") and a "Done when"
column that ends in "(done ...)" once the milestone is finished. The roadmap
groups the rows by phase and says which are finished and what the rest wait
for. Standard library only.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / "docs" / "DESIGN.md"
ROADMAP = ROOT / "docs" / "ROADMAP.md"


def split_row(line):
    """Cells of a Markdown table row; `|` inside backticks stays in the cell."""
    cells, cell, code = [], "", False
    for c in line.strip()[1:-1]:
        if c == "`":
            code = not code
        if c == "|" and not code:
            cells.append(cell.strip())
            cell = ""
        else:
            cell += c
    cells.append(cell.strip())
    return cells


def milestones(text):
    start = text.index("## 6. Milestones")
    rows = []
    in_table = False
    for line in text[start:].splitlines():
        if line.startswith("| # |"):
            in_table = True
            continue
        if not in_table:
            continue
        if line.startswith("|---"):
            continue
        if not line.startswith("|"):
            break
        cells = split_row(line)
        if len(cells) < 3:
            continue
        rows.append(cells[:3])
    return rows


def title_and_scope(phase):
    m = re.match(r"\*\*(.+?)\*\*\s*(.*)", phase)
    if not m:
        return phase, ""
    title = m.group(1).rstrip(":")
    scope = m.group(2).lstrip(":").strip()
    # Keep the section reference with the title, the rest as the scope.
    ref = re.match(r"(\(§[^)]*\))\s*:?\s*(.*)", scope)
    if ref:
        return f"{title} {ref.group(1)}", ref.group(2)
    return title, scope


def status(done_when):
    m = re.search(r"\(done\b", done_when)
    if not m:
        return "Planned", done_when
    goal = done_when[: m.start()].strip()
    detail = done_when[m.start():]
    if re.match(r"\(done on ", detail):
        return "Partly done", goal
    return "Done", goal


def phase_of(number):
    return number.split(".")[0]


def render(rows):
    out = [
        "# Roadmap",
        "",
        "<!-- Generated by tools/gen_roadmap.py from docs/DESIGN.md section 6; do not edit. -->",
        "",
        "Where Cuervo Engine is going, phase by phase. Each milestone has a goal it is \"done\"",
        "when; the design behind each one is in [DESIGN.md](DESIGN.md) (the section after its",
        "title), and what works today is in [STATUS.md](STATUS.md). Changing the roadmap is a",
        "design change, described in CONTRIBUTING.md (\"Design Changes\").",
        "",
    ]
    done = sum(1 for r in rows if status(r[2])[0] == "Done")
    out.append(f"{done} of {len(rows)} milestones are done.")
    out.append("")
    current = None
    for number, phase, done_when in rows:
        major = phase_of(number)
        title, scope = title_and_scope(phase)
        state, goal = status(done_when)
        if number == major:
            current = major
            out += [f"## Phase {number}: {title}", ""]
            if scope:
                out += [scope, ""]
            out += [f"**{state}.** Done when: {goal}", ""]
            continue
        if current != major:
            current = major
            out += [f"## Phase {major}", ""]
        out += [f"- **{number} {title}** ({state.lower()}). {scope}".rstrip(),
                f"  Done when: {goal}", ""]
    return "\n".join(out).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(milestones(DESIGN.read_text(encoding="utf-8")))
    if args.write:
        ROADMAP.write_text(text, encoding="utf-8")
        print(f"roadmap written to {ROADMAP.relative_to(ROOT)}")
        return 0
    current = ROADMAP.read_text(encoding="utf-8") if ROADMAP.exists() else ""
    if current != text:
        print("docs/ROADMAP.md is out of date: run python3 -I tools/gen_roadmap.py --write", file=sys.stderr)
        return 1
    print("docs/ROADMAP.md is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
