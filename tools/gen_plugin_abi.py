#!/usr/bin/env python3
"""Generates the Rust and C# declarations of the plugin ABI (milestone 10.5c).

    python3 -I tools/gen_plugin_abi.py --write   # bindings/rust/.../sys.rs and bindings/dotnet/.../Abi.g.cs
    python3 -I tools/gen_plugin_abi.py --check   # exit 1 when either is out of date (a ctest)

The C header cuervo/plugin/cuervo_plugin.h is the one definition of the ABI
(DESIGN.md 4.18 "Decision": the Rust crate is generated from it; the C#
binding's raw layer is too, so neither can drift from the header). This reads
the small, regular subset of C it is written in: #define constants, an
anonymous enum of constants, opaque struct typedefs, function pointer
typedefs and the cuervo_host struct of function pointers. Standard library
only, so no bindgen or libclang is needed.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "cuervo" / "plugin" / "cuervo_plugin.h"
OUT = ROOT / "bindings" / "rust" / "cuervo-plugin" / "src" / "sys.rs"
OUT_CS = ROOT / "bindings" / "dotnet" / "Cuervo.Plugin" / "Abi.g.cs"

CS_SCALARS = {
    "void": "void",
    "int": "int",
    "uint8_t": "byte",
    "uint32_t": "uint",
    "int32_t": "int",
    "int64_t": "long",
    "size_t": "nuint",
    "float": "float",
    "double": "double",
    "char": "byte",
}

SCALARS = {
    "void": "()",
    "int": "c_int",
    "uint8_t": "u8",
    "uint32_t": "u32",
    "int32_t": "i32",
    "int64_t": "i64",
    "size_t": "usize",
    "float": "f32",
    "double": "f64",
    "char": "c_char",
}

RUST_KEYWORDS = {"fn", "type", "ref", "self", "mod", "use", "impl", "match", "move", "box", "in", "loop"}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def rust_type(c, opaque):
    c = " ".join(c.replace("*", " * ").split())
    stars = c.count("*")
    base = c.replace("*", "").strip()
    const = base.startswith("const ")
    base = base.replace("const ", "").strip()
    if base in SCALARS:
        r = SCALARS[base]
    elif base in opaque or base.startswith("cuervo_"):
        r = base
    else:
        raise SystemExit(f"gen_plugin_abi: unknown C type '{c}'")
    if stars == 0:
        return r
    if r == "()":
        r = "c_void"
    for i in range(stars):
        r = ("*const " if const and i == 0 else "*mut ") + r
    return r


def param(p, opaque):
    p = p.strip()
    if p == "void" or not p:
        return None
    m = re.match(r"(.*?)([A-Za-z_][A-Za-z0-9_]*)$", p)
    ctype, name = m.group(1), m.group(2)
    if name in RUST_KEYWORDS:
        name += "_"
    return f"{name}: {rust_type(ctype, opaque)}"


def fn_type(ret, params, opaque):
    ps = [x for x in (param(p, opaque) for p in params.split(",")) if x]
    r = rust_type(ret, opaque)
    tail = "" if r == "()" else f" -> {r}"
    return f'unsafe extern "C" fn({", ".join(ps)}){tail}'


def generate():
    src = strip_comments(HEADER.read_text())
    out = [
        "// Generated by tools/gen_plugin_abi.py from cuervo/plugin/cuervo_plugin.h. Do not edit.",
        "// The raw plugin ABI; the safe wrapper is in lib.rs.",
        "#![allow(non_camel_case_types, non_upper_case_globals, dead_code)]",
        "",
        "use core::ffi::{c_char, c_int, c_void};",
        "",
    ]
    for name, value in re.findall(r"#define\s+(CUERVO_[A-Z_]+)\s+(\d+)", src):
        out.append(f"pub const {name}: u32 = {value};")
    for body in re.findall(r"enum\s*\{([^}]*)\}", src):
        for name, value in re.findall(r"(CUERVO_[A-Z_]+)\s*=\s*(\d+)", body):
            out.append(f"pub const {name}: c_int = {value};")
    out.append("")
    opaque = re.findall(r"typedef\s+struct\s+(cuervo_\w+)\s+\1\s*;", src)
    for name in opaque:
        out.append("#[repr(C)]")
        out.append(f"pub struct {name} {{")
        out.append("    _private: [u8; 0],")
        out.append("}")
    out.append("")
    for ret, name, params in re.findall(r"typedef\s+([\w\s\*]+?)\s*\(\s*\*\s*(\w+)\s*\)\s*\(([^)]*)\)\s*;", src):
        out.append(f"pub type {name} = Option<{fn_type(ret, params, opaque)}>;")
    out.append("")
    host = re.search(r"typedef\s+struct\s+cuervo_host\s*\{(.*?)\}\s*cuervo_host\s*;", src, re.S)
    if not host:
        raise SystemExit("gen_plugin_abi: no cuervo_host struct")
    out.append("#[repr(C)]")
    out.append("pub struct cuervo_host {")
    for decl in host.group(1).split(";"):
        decl = " ".join(decl.split())
        if not decl:
            continue
        m = re.match(r"(.+?)\s*\(\s*\*\s*(\w+)\s*\)\s*\((.*)\)$", decl)
        if m:
            ret, name, params = m.groups()
            out.append(f"    pub {name}: Option<{fn_type(ret, params, opaque)}>,")
            continue
        m = re.match(r"(.+?)\s*(\w+)$", decl)
        ctype, name = m.groups()
        out.append(f"    pub {name}: {rust_type(ctype, opaque)},")
    out.append("}")
    m = re.search(r"typedef\s+int\s*\(\s*\*\s*cuervo_plugin_entry_fn\s*\)", src)
    if not m:
        raise SystemExit("gen_plugin_abi: no cuervo_plugin_entry_fn")
    return "\n".join(out) + "\n"


def cs_type(c, opaque):
    c = " ".join(c.replace("*", " * ").split())
    stars = c.count("*")
    base = c.replace("*", "").replace("const ", "").strip()
    if base in opaque or (base.startswith("cuervo_") and base.endswith("_fn")):
        # Opaque handles and function pointers cross as plain addresses.
        return "IntPtr" if stars <= 1 else "IntPtr*"
    if base not in CS_SCALARS:
        raise SystemExit(f"gen_plugin_abi: unknown C type '{c}'")
    return CS_SCALARS[base] + "*" * stars


def cs_fn(ret, params, opaque):
    types = []
    for p in params.split(","):
        p = p.strip()
        if not p or p == "void":
            continue
        m = re.match(r"(.*?)([A-Za-z_][A-Za-z0-9_]*)$", p)
        types.append(cs_type(m.group(1), opaque))
    types.append(cs_type(ret, opaque))
    return f"delegate* unmanaged<{', '.join(types)}>"


def generate_cs():
    src = strip_comments(HEADER.read_text())
    opaque = re.findall(r"typedef\s+struct\s+(cuervo_\w+)\s+\1\s*;", src)
    out = [
        "// Generated by tools/gen_plugin_abi.py from cuervo/plugin/cuervo_plugin.h. Do not edit.",
        "// The raw plugin ABI; the safe wrapper is in Plugin.cs.",
        "#pragma warning disable CS8981, IDE1006 // C names",
        "using System;",
        "using System.Runtime.InteropServices;",
        "",
        "namespace Cuervo.Plugin.Abi;",
        "",
        "public static class Constants",
        "{",
    ]
    for name, value in re.findall(r"#define\s+(CUERVO_[A-Z_]+)\s+(\d+)", src):
        out.append(f"    public const uint {name} = {value};")
    for body in re.findall(r"enum\s*\{([^}]*)\}", src):
        for name, value in re.findall(r"(CUERVO_[A-Z_]+)\s*=\s*(\d+)", body):
            out.append(f"    public const int {name} = {value};")
    out.append("}")
    out.append("")
    host = re.search(r"typedef\s+struct\s+cuervo_host\s*\{(.*?)\}\s*cuervo_host\s*;", src, re.S)
    out.append("[StructLayout(LayoutKind.Sequential)]")
    out.append("public unsafe struct cuervo_host")
    out.append("{")
    for decl in host.group(1).split(";"):
        decl = " ".join(decl.split())
        if not decl:
            continue
        m = re.match(r"(.+?)\s*\(\s*\*\s*(\w+)\s*\)\s*\((.*)\)$", decl)
        if m:
            ret, name, params = m.groups()
            out.append(f"    public {cs_fn(ret, params, opaque)} {name};")
            continue
        m = re.match(r"(.+?)\s*(\w+)$", decl)
        ctype, name = m.groups()
        out.append(f"    public {cs_type(ctype, opaque)} {name};")
    out.append("}")
    return "\n".join(out) + "\n"


def main(argv):
    outputs = [(OUT, generate()), (OUT_CS, generate_cs())]
    if "--write" in argv:
        for path, text in outputs:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
        return 0
    if "--check" in argv:
        stale = [p for p, text in outputs if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"gen_plugin_abi: {p.relative_to(ROOT)} is out of date: run python3 -I tools/gen_plugin_abi.py --write")
        return 1 if stale else 0
    for _, text in outputs:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
